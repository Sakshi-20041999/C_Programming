#include <stdio.h>

////////////////////////////////////////////////////////////////////
//
//  Function Name : DisplayASCII
//  Description   : Displays ASCII values with Decimal, Hex and Octal
//  Input         : ---
//  Output        : ASCII Table
//  Author        : Sakshi Santosh Jadhav
//  Date          : 27/11/2025
//
////////////////////////////////////////////////////////////////////

void DisplayASCII()
{
    int i = 0;

    printf("Symbol\tDecimal\tHex\tOctal\n");

    for(i = 0; i <= 255; i++)
    {
        printf("%c\t%d\t%X\t%o\n", i, i, i, i);
    }
}

////////////////////////////////////////////////////////////////////
//
//  Entry Point Function
//
////////////////////////////////////////////////////////////////////

int main()
{
    DisplayASCII();
    return 0;
}

