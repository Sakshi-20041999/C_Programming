#include<stdio.h>

////////////////////////////////////////////////////////////////////////////////////
//
// Function Name : Accept
// Description   : Displays '*' on screen for given number of times
// Input         : Integer
// Output        : Pattern
// Author        : Sakshi Santosh Jadhav
// Date          : 20/10/2025
//
////////////////////////////////////////////////////////////////////////////////////

void Accept(int iNo)
{
    int iCnt = 0;

    for(iCnt = 1; iCnt <= iNo; iCnt++)
    {
        printf("* ");
    }
}

////////////////////////////////////////////////////////////////////////////////////
//
// Entry Point Function
//
////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;

    printf("Enter number: ");
    scanf("%d", &iValue);

    Accept(iValue);

    return 0;
}

