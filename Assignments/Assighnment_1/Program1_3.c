#include<stdio.h>

////////////////////////////////////////////////////////////////////////////////////
//
// Function Name : Display
// Description   : Displays numbers from 5 to 1
// Input         : None
// Output        : Numbers
// Author        : Sakshi Santosh Jadhav
// Date          : 20/10/2025
//
////////////////////////////////////////////////////////////////////////////////////

void Display()
{
    int i = 5;
    while(i >= 1)
    {
        printf("%d\n", i);
        i--;
    }
}

////////////////////////////////////////////////////////////////////////////////////
//
// Entry Point Function
//
////////////////////////////////////////////////////////////////////////////////////

int main()
{
    Display();
    return 0;
}

