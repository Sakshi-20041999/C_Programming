#include<stdio.h>

////////////////////////////////////////////////////////////////////
//
//  Function Name : Display
//  Description   : Display capital letters A to F using recursion
//  Input         : None
//  Output        : A B C D E F
//  Author        : Sakshi Santosh Jadhav
//  Date          : 01/12/2025
//
////////////////////////////////////////////////////////////////////

void Display()
{
    static char ch = 'A';

    if(ch <= 'F')
    {
        printf("%c\t", ch);
        ch++;
        Display();
    }
}

////////////////////////////////////////////////////////////////////
//
//  Entry Point Function
//
////////////////////////////////////////////////////////////////////

int main()
{
    Display();
    return 0;
}

