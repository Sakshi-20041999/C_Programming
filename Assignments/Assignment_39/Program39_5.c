#include<stdio.h>

////////////////////////////////////////////////////////////////////
//
//  Function Name : Display
//  Description   : Display small letters a to f using recursion
//  Input         : None
//  Output        : a b c d e f
//  Author        : Sakshi Santosh Jadhav
//  Date          : 01/12/2025
//
////////////////////////////////////////////////////////////////////

void Display()
{
    static char ch = 'a';

    if(ch <= 'f')
    {
        printf("%c\t", ch);
        ch++;
        Display();
    }
}

////////////////////////////////////////////////////////////////////
//
//  Entry Point Function
//
////////////////////////////////////////////////////////////////////

int main()
{
    Display();
    return 0;
}

