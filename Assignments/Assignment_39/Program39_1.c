#include<stdio.h>

////////////////////////////////////////////////////////////////////
//
//  Function Name : Display
//  Description   : Display * five times using recursion
//  Input         : None
//  Output        : *
//  Author        : Sakshi Santosh Jadhav
//  Date          : 01/12/2025
//
////////////////////////////////////////////////////////////////////

void Display()
{
    static int i = 1;

    if(i <= 5)
    {
        printf("*\t");
        i++;
        Display();
    }
}

////////////////////////////////////////////////////////////////////
//
//  Entry Point Function
//
////////////////////////////////////////////////////////////////////

int main()
{
    Display();
    return 0;
}

