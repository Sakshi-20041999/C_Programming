#include<stdio.h>

////////////////////////////////////////////////////////////////////
//
//  Function Name : Display
//  Description   : Display numbers from 5 to 1 using recursion
//  Input         : None
//  Output        : 5 4 3 2 1
//  Author        : Sakshi Santosh Jadhav
//  Date          : 01/12/2025
//
////////////////////////////////////////////////////////////////////

void Display()
{
    static int i = 5;

    if(i >= 1)
    {
        printf("%d\t", i);
        i--;
        Display();
    }
}

////////////////////////////////////////////////////////////////////
//
//  Entry Point Function
//
////////////////////////////////////////////////////////////////////

int main()
{
    Display();
    return 0;
}

