#include<stdio.h>

////////////////////////////////////////////////////////////////////
//
// Function Name :  CountFactors
// Description   :  Counts total factors of given number
// Input         :  Integer
// Output        :  Integer
// Author        :  Sakshi Santosh Jadhav
//
////////////////////////////////////////////////////////////////////

int CountFactors(int iNo)
{
    int iCnt = 0, iCount = 0;

    for(iCnt = 1; iCnt <= iNo; iCnt++)
    {
        if(iNo % iCnt == 0)
        {
            iCount++;
        }
    }
    return iCount;
}

////////////////////////////////////////////////////////////////////
//
// Entry Point Function
//
////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0, iRet = 0;

    printf("Enter number: ");
    scanf("%d", &iValue);

    iRet = CountFactors(iValue);

    printf("Total factors: %d\n", iRet);

    return 0;
}

