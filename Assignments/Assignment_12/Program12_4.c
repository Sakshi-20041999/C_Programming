#include<stdio.h>

////////////////////////////////////////////////////////////////////
//
// Function Name :  SumEvenFactors
// Description   :  Calculates sum of even factors excluding the number
// Input         :  Integer
// Output        :  Integer
// Author        :  Sakshi Santosh Jadhav
//
////////////////////////////////////////////////////////////////////

int SumEvenFactors(int iNo)
{
    int iCnt = 0, iSum = 0;

    for(iCnt = 1; iCnt < iNo; iCnt++)
    {
        if((iNo % iCnt == 0) && (iCnt % 2 == 0))
        {
            iSum = iSum + iCnt;
        }
    }
    return iSum;
}

////////////////////////////////////////////////////////////////////
//
// Entry Point Function
//
////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0, iRet = 0;

    printf("Enter number: ");
    scanf("%d", &iValue);

    iRet = SumEvenFactors(iValue);

    printf("Sum of even factors: %d\n", iRet);

    return 0;
}

