#include<stdio.h>

////////////////////////////////////////////////////////////////////
//
// Function Name :  PrintOddNumbers
// Description   :  Displays odd numbers up to given limit
// Input         :  Integer
// Output        :  Prints odd numbers
// Author        :  Sakshi Santosh Jadhav
//
////////////////////////////////////////////////////////////////////

void PrintOddNumbers(int iLimit)
{
    int iCnt = 0;

    for(iCnt = 1; iCnt <= iLimit; iCnt = iCnt + 2)
    {
        printf("%d ", iCnt);
    }
}

////////////////////////////////////////////////////////////////////
//
// Entry Point Function
//
////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;

    printf("Enter number: ");
    scanf("%d", &iValue);

    PrintOddNumbers(iValue);

    return 0;
}

