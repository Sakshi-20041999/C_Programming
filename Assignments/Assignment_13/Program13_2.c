#include<stdio.h>

////////////////////////////////////////////////////////////////////
//
// Function Name :  PrintEvenNumbers
// Description   :  Displays even numbers up to given limit
// Input         :  Integer
// Output        :  Prints even numbers
// Author        :  Sakshi Santosh Jadhav
//
////////////////////////////////////////////////////////////////////

void PrintEvenNumbers(int iLimit)
{
    int iCnt = 0;

    for(iCnt = 2; iCnt <= iLimit; iCnt = iCnt + 2)
    {
        printf("%d ", iCnt);
    }
}

////////////////////////////////////////////////////////////////////
//
// Entry Point Function
//
////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;

    printf("Enter number: ");
    scanf("%d", &iValue);

    PrintEvenNumbers(iValue);

    return 0;
}

