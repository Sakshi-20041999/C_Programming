#include <stdio.h>

////////////////////////////////////////////////////////////////////
//
// Function Name : DollarToINR
// Description   : Converts USD to INR (1 USD = 70 INR)
// Input         : Integer
// Output        : Integer
// Author        : Sakshi Santosh Jadhav
// Date          : 21/11/2025
//
////////////////////////////////////////////////////////////////////

int DollarToINR(int iNo)
{
    int iResult = 0;

    iResult = iNo * 70;
    return iResult;
}

////////////////////////////////////////////////////////////////////
//
// Entry point Function
//
////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0, iRet = 0;

    printf("Enter number of USD: ");
    scanf("%d", &iValue);

    iRet = DollarToINR(iValue);

    printf("Value in INR is %d\n", iRet);

    return 0;
}

