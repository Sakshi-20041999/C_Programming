#include<stdio.h>

////////////////////////////////////////////////////////////////////
//
// Function Name : StrCpyRev
// Description   : Copies string in reverse order into destination
// Input         : Character pointer, Character pointer
// Output        : Modified destination string
// Author        : Sakshi Santosh Jadhav
// Date          : 27/11/2025
//
////////////////////////////////////////////////////////////////////

void StrCpyRev(char *src, char *dest)
{
    char *end = src;

    while(*end != '\0')
    {
        end++;
    }
    end--;

    while(end >= src)
    {
        *dest = *end;
        dest++;
        end--;
    }
    *dest = '\0';
}

////////////////////////////////////////////////////////////////////
//
// Entry Point Function
//
////////////////////////////////////////////////////////////////////

int main()
{
    char arr[30] = "Marvellous Python";
    char brr[30];

    StrCpyRev(arr, brr);

    printf("%s", brr);
    return 0;
}

