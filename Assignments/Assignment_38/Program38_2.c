#include<stdio.h>

////////////////////////////////////////////////////////////////////
//
// Function Name : StrCpyX
// Description   : Copies string by removing spaces
// Input         : Character pointer, Character pointer
// Output        : Modified destination string
// Author        : Sakshi Santosh Jadhav
// Date          : 27/11/2025
//
////////////////////////////////////////////////////////////////////

void StrCpyX(char *src, char *dest)
{
    while(*src != '\0')
    {
        if(*src != ' ')
        {
            *dest = *src;
            dest++;
        }
        src++;
    }
    *dest = '\0';
}

////////////////////////////////////////////////////////////////////
//
// Entry Point Function
//
////////////////////////////////////////////////////////////////////

int main()
{
    char arr[30] = "Marvel   lous Pyth   on";
    char brr[30];

    StrCpyX(arr, brr);

    printf("%s", brr);
    return 0;
}

