#include<stdio.h>

////////////////////////////////////////////////////////////////////
//
//  Function Name : CountCapital
//  Description   : Counts number of capital letters in string
//  Input         : Character pointer
//  Output        : Integer
//  Author        : Sakshi Santosh Jadhav
//  Date          : 27/11/2025
//
////////////////////////////////////////////////////////////////////

int CountCapital(char *str)
{
    int iCnt = 0;

    while(*str != '\0')
    {
        if(*str >= 'A' && *str <= 'Z')
        {
            iCnt++;
        }
        str++;
    }
    return iCnt;
}

////////////////////////////////////////////////////////////////////
//
//  Entry Point Function
//
////////////////////////////////////////////////////////////////////

int main()
{
    char arr[20];
    int iRet = 0;

    printf("Enter string: ");
    scanf("%[^\n]s", arr);

    iRet = CountCapital(arr);

    printf("Capital count is: %d", iRet);

    return 0;
}

