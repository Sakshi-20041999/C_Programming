#include<stdio.h>

////////////////////////////////////////////////////////////////////
//
// Function Name :  DisplayDigit
// Description   :  Displays digits of the given number
// Input         :  Integer
// Output        :  Digits (one per line)
// Author        :  Sakshi Santosh Jadhav
//
////////////////////////////////////////////////////////////////////

void DisplayDigit(int iNo)
{
    int iDigit = 0;

    if(iNo < 0)
    {
        iNo = -iNo;
    }

    while(iNo != 0)
    {
        iDigit = iNo % 10;
        printf("%d\n", iDigit);
        iNo = iNo / 10;
    }
}

////////////////////////////////////////////////////////////////////
//
// Entry Point Function
//
////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;

    printf("Enter number: ");
    scanf("%d", &iValue);

    DisplayDigit(iValue);

    return 0;
}

