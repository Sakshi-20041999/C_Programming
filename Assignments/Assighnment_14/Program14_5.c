#include<stdio.h>

////////////////////////////////////////////////////////////////////
//
// Function Name :  Count
// Description   :  Counts digits which are less than 6
// Input         :  Integer
// Output        :  Integer
// Author        :  Sakshi Santosh Jadhav
//
////////////////////////////////////////////////////////////////////

int Count(int iNo)
{
    int iDigit = 0, iCnt = 0;

    if(iNo < 0)
    {
        iNo = -iNo;
    }

    while(iNo > 0)
    {
        iDigit = iNo % 10;
        if(iDigit < 6)
        {
            iCnt++;
        }
        iNo = iNo / 10;
    }
    return iCnt;
}

////////////////////////////////////////////////////////////////////
//
// Entry Point Function
//
////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0, iRet = 0;

    printf("Enter number: ");
    scanf("%d", &iValue);

    iRet = Count(iValue);

    printf("Count of digits less than 6 is: %d\n", iRet);

    return 0;
}

