#include<stdio.h>

////////////////////////////////////////////////////////////////////
//
//  Function Name : strlwrx
//  Description   : Converts all characters of string into lowercase
//  Input         : Character pointer
//  Output        : Modified string
//  Author        : Sakshi Santosh Jadhav
//  Date          : 27/11/2025
//
////////////////////////////////////////////////////////////////////

void strlwrx(char *str)
{
    while(*str != '\0')
    {
        if(*str >= 'A' && *str <= 'Z')
        {
            *str = *str + 32;
        }
        str++;
    }
}

////////////////////////////////////////////////////////////////////
//
//  Entry Point Function
//
////////////////////////////////////////////////////////////////////

int main()
{
    char arr[50];

    printf("Enter string: ");
    scanf("%[^\n]s", arr);

    strlwrx(arr);

    printf("Modified string is %s", arr);

    return 0;
}

