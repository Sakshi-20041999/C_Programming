#include<stdio.h>

////////////////////////////////////////////////////////////////////
//
//  Function Name : CountWhite
//  Description   : Counts number of white spaces in string
//  Input         : Character pointer
//  Output        : Integer
//  Author        : Sakshi Santosh Jadhav
//  Date          : 27/11/2025
//
////////////////////////////////////////////////////////////////////

int CountWhite(char *str)
{
    int iCnt = 0;

    while(*str != '\0')
    {
        if(*str == ' ')
        {
            iCnt++;
        }
        str++;
    }
    return iCnt;
}

////////////////////////////////////////////////////////////////////
//
//  Entry Point Function
//
////////////////////////////////////////////////////////////////////

int main()
{
    char arr[100];
    int iRet = 0;

    printf("Enter string: ");
    scanf("%[^\n]s", arr);

    iRet = CountWhite(arr);

    printf("%d", iRet);

    return 0;
}

