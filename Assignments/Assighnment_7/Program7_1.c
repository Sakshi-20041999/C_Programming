#include <stdio.h>

////////////////////////////////////////////////////////////////////
//
// Function Name : DisplayPattern
// Description   : Displays pattern of $ and * alternately
// Input         : Integer
// Output        : Pattern
// Author        : Sakshi Santosh Jadhav
// Date          : 7/11/2025
//
////////////////////////////////////////////////////////////////////

void DisplayPattern(int iNo)
{
    int i = 0;

    for(i = 1; i <= iNo; i++)
    {
        if(i % 2 == 0)
        {
            printf("* ");
        }
        else
        {
            printf("$ ");
        }
    }
}

////////////////////////////////////////////////////////////////////
//
// Entry point Function
//
////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;

    printf("Enter number: ");
    scanf("%d", &iValue);

    DisplayPattern(iValue);

    return 0;
}

