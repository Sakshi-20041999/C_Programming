#include<stdio.h>

////////////////////////////////////////////////////////////////////
//
// Function Name : OddDisplay
// Description   : Displays odd numbers from 1 to given number
// Input         : Integer
// Output        : Numbers
// Author        : Sakshi Santosh Jadhav
// Date          : 7/11/2025
//
////////////////////////////////////////////////////////////////////

void OddDisplay(int iNo)
{
    int iCnt = 0;

    for(iCnt = 1; iCnt <= iNo; iCnt++)
    {
        if(iCnt % 2 != 0)
        {
            printf("%d\t", iCnt);
        }
    }
}

////////////////////////////////////////////////////////////////////
//
// Entry point Function
//
////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;

    printf("Enter number: ");
    scanf("%d", &iValue);

    OddDisplay(iValue);

    return 0;
}

