#include<stdio.h>

////////////////////////////////////////////////////////////////////////////////////
//
// Function Name : Display
// Description   : Displays '*' on screen using while loop
// Input         : Integer
// Output        : Pattern
// Author        : Sakshi Santosh Jadhav
// Date          : 20/10/2025
//
////////////////////////////////////////////////////////////////////////////////////

void Display(int iNo)
{
    int iCnt = 0;

    while(iCnt < iNo)
    {
        printf("* ");
        iCnt++;
    }
}

////////////////////////////////////////////////////////////////////////////////////
//
// Entry Point Function
//
////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;

    printf("Enter number: ");
    scanf("%d", &iValue);

    Display(iValue);

    return 0;
}

