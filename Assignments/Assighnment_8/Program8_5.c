#include<stdio.h>

////////////////////////////////////////////////////////////////////
//
// Function Name : ReverseTable
// Description   : Prints the reverse multiplication table of a number
// Input         : Integer
// Output        : Numbers
// Author        : Sakshi Santosh Jadhav
// Date          : 21/11/2025
//
////////////////////////////////////////////////////////////////////

void ReverseTable(int iNo)
{
    int iCnt = 0;

    if(iNo < 0)
    {
        iNo = -iNo;
    }

    for(iCnt = 10; iCnt >= 1; iCnt--)
    {
        printf("%d\t", iNo * iCnt);
    }
    printf("\n");
}

////////////////////////////////////////////////////////////////////
//
// Entry point Function for the application
//
////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;

    printf("Enter the number : ");
    scanf("%d", &iValue);

    ReverseTable(iValue);

    return 0;
}

