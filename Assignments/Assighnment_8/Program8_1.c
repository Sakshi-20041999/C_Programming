#include <stdio.h>

////////////////////////////////////////////////////////////////////
//
// Function Name : Number
// Description   : Displays whether number is Small, Medium or Large
// Input         : Integer
// Output        : Text
// Author        : Sakshi Santosh Jadhav
// Date          : 7/11/2025
//
////////////////////////////////////////////////////////////////////

void Number(int iNo)
{
    if (iNo < 50)
    {
        printf("Small\n");
    }
    else if (iNo >= 50 && iNo < 100)
    {
        printf("Medium\n");
    }
    else
    {
        printf("Large\n");
    }
}

////////////////////////////////////////////////////////////////////
//
// Entry point Function
//
////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;

    printf("Enter number: ");
    scanf("%d", &iValue);

    Number(iValue);

    return 0;
}

