#include<stdio.h>

////////////////////////////////////////////////////////////////////
//
// Function Name :  PrintFactors
// Description   :  Displays all factors of the given number
// Input         :  Integer
// Output        :  Prints factors
// Author        :  Sakshi Santosh Jadhav
//
////////////////////////////////////////////////////////////////////

void PrintFactors(int iNo)
{
    int iCnt = 0;

    for(iCnt = 1; iCnt <= iNo; iCnt++)
    {
        if(iNo % iCnt == 0)
        {
            printf("%d ", iCnt);
        }
    }
}

////////////////////////////////////////////////////////////////////
//
// Entry Point Function
//
////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;

    printf("Enter number: ");
    scanf("%d", &iValue);

    PrintFactors(iValue);

    return 0;
}

