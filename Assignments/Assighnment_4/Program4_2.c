#include <stdio.h>

////////////////////////////////////////////////////////////////////////////////////
//
// Function Name : FactRev
// Description   : Displays factors of a number in reverse order
// Input         : Integer
// Output        : Numbers
// Author        : Sakshi Santosh Jadhav
// Date          : 20/10/2025
//
////////////////////////////////////////////////////////////////////////////////////

void FactRev(int iNo)
{
    int iCnt = 0;

    for(iCnt = iNo / 2; iCnt >= 1; iCnt--)
    {
        if(iNo % iCnt == 0)
        {
            printf("%d ", iCnt);
        }
    }
}

////////////////////////////////////////////////////////////////////////////////////
//
// Entry Point Function
//
////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;

    printf("Enter number: ");
    scanf("%d", &iValue);

    FactRev(iValue);

    return 0;
}

