#include <stdio.h>

////////////////////////////////////////////////////////////////////////////////////
//
// Function Name : NonFact
// Description   : Displays all non-factors of a number
// Input         : Integer
// Output        : Numbers
// Author        : Sakshi Santosh Jadhav
// Date          : 20/10/2025
//
////////////////////////////////////////////////////////////////////////////////////

void NonFact(int iNo)
{
    int iCnt = 0;

    for(iCnt = 1; iCnt < iNo; iCnt++)
    {
        if(iNo % iCnt != 0)
        {
            printf("%d ", iCnt);
        }
    }
}

////////////////////////////////////////////////////////////////////////////////////
//
// Entry Point Function
//
////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;

    printf("Enter number: ");
    scanf("%d", &iValue);

    NonFact(iValue);

    return 0;
}

