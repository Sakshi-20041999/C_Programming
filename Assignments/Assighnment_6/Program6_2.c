#include<stdio.h>
#include<stdbool.h>

////////////////////////////////////////////////////////////////////
//
// Function Name : CheckGreater
// Description   : Checks whether number is greater than 100
// Input         : Integer
// Output        : Boolean
// Author        : Sakshi Santosh Jadhav
// Date          : 20/11/2025
//
////////////////////////////////////////////////////////////////////

bool CheckGreater(int iNo)
{
    if(iNo > 100)
    {
        return true;
    }
    else
    {
        return false;
    }
}

////////////////////////////////////////////////////////////////////
//
// Entry point Function
//
////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;
    bool bRet = false;

    printf("Enter number : ");
    scanf("%d", &iValue);

    bRet = CheckGreater(iValue);

    if(bRet == true)
    {
        printf("Greater");
    }
    else
    {
        printf("Smaller");
    }

    return 0;
}

