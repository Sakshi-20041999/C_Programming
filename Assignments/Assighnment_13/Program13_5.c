#include<stdio.h>

////////////////////////////////////////////////////////////////////
//
// Function Name :  SumEvenNumbers
// Description   :  Calculates sum of first N even numbers
// Input         :  Integer
// Output        :  Integer
// Author        :  Sakshi Santosh Jadhav
//
////////////////////////////////////////////////////////////////////

int SumEvenNumbers(int iLimit)
{
    int iCnt = 0;
    int iSum = 0;

    for(iCnt = 2; iCnt <= iLimit * 2; iCnt = iCnt + 2)
    {
        iSum = iSum + iCnt;
    }
    return iSum;
}

////////////////////////////////////////////////////////////////////
//
// Entry Point Function
//
////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;
    int iRet = 0;

    printf("Enter number: ");
    scanf("%d", &iValue);

    iRet = SumEvenNumbers(iValue);

    printf("Sum = %d\n", iRet);

    return 0;
}

