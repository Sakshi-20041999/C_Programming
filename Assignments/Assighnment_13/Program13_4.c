#include<stdio.h>

////////////////////////////////////////////////////////////////////
//
// Function Name :  SumNaturalNumbers
// Description   :  Calculates sum of first N natural numbers
// Input         :  Integer
// Output        :  Integer
// Author        :  Sakshi Santosh Jadhav
//
////////////////////////////////////////////////////////////////////

int SumNaturalNumbers(int iLimit)
{
    int iCnt = 0;
    int iSum = 0;

    for(iCnt = 1; iCnt <= iLimit; iCnt++)
    {
        iSum = iSum + iCnt;
    }
    return iSum;
}

////////////////////////////////////////////////////////////////////
//
// Entry Point Function
//
////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;
    int iRet = 0;

    printf("Enter number: ");
    scanf("%d", &iValue);

    iRet = SumNaturalNumbers(iValue);

    printf("Sum = %d\n", iRet);

    return 0;
}

