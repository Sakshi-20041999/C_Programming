#include<stdio.h>

////////////////////////////////////////////////////////////////////
//
// Function Name :  PrintNumbers
// Description   :  Displays numbers from 1 to given limit
// Input         :  Integer
// Output        :  Prints numbers
// Author        :  Sakshi Santosh Jadhav
//
////////////////////////////////////////////////////////////////////

void PrintNumbers(int iLimit)
{
    int iCnt = 0;

    for(iCnt = 1; iCnt <= iLimit; iCnt++)
    {
        printf("%d ", iCnt);
    }
}

////////////////////////////////////////////////////////////////////
//
// Entry Point Function
//
////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;

    printf("Enter number: ");
    scanf("%d", &iValue);

    PrintNumbers(iValue);

    return 0;
}

